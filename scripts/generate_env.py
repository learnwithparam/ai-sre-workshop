"""Add every missing generated secret to .env. Never overwrites a value, never prints one.

Two values cannot be generated and must be pasted in by you: HYPERDX_API_KEY (HyperDX, Team
Settings) and ANTHROPIC_API_KEY (console.anthropic.com, API keys).
"""

import secrets
import sys
from pathlib import Path

ENV = Path(__file__).resolve().parent.parent / ".env"
FROM_YOU = ("HYPERDX_API_KEY", "ANTHROPIC_API_KEY")
GENERATED = {
    "CLICKHOUSE_READER_PASSWORD": lambda: secrets.token_urlsafe(24),
    "CLICKHOUSE_WRITER_PASSWORD": lambda: secrets.token_urlsafe(24),
    "CLICKHOUSE_MCP_AUTH_TOKEN": lambda: secrets.token_urlsafe(32),
    "SRE_MCP_TOKEN": lambda: secrets.token_urlsafe(32),
    "SRE_SESSION_SECRET": lambda: secrets.token_urlsafe(32),
    "SRE_APPROVER_EMAIL": lambda: "oncall@example.com",
    "SRE_APPROVER_PASSWORD": lambda: secrets.token_urlsafe(12),
    "LIBRECHAT_USER_EMAIL": lambda: "sre@example.com",
    "LIBRECHAT_USER_PASSWORD": lambda: secrets.token_urlsafe(12),
    "HYPERDX_USER_EMAIL": lambda: "workshop@example.com",
    "HYPERDX_USER_PASSWORD": lambda: secrets.token_urlsafe(12),
    "JWT_SECRET": lambda: secrets.token_hex(32),
    "JWT_REFRESH_SECRET": lambda: secrets.token_hex(32),
    "CREDS_KEY": lambda: secrets.token_hex(32),
    "CREDS_IV": lambda: secrets.token_hex(16),
}


def read(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    pairs = (line.split("=", 1) for line in path.read_text().splitlines() if "=" in line and line[0] != "#")
    return {key.strip(): value.strip() for key, value in pairs}


PLACEHOLDER = "change-me"


def unset(current: dict[str, str], key: str) -> bool:
    """A copy of the example file holds `change-me` for every secret, which is not a value."""
    return current.get(key, "") in ("", PLACEHOLDER)


def write(path: Path, values: dict[str, str]) -> None:
    """Replace a key's line where the file already has one, so a copied example gains no duplicates."""
    lines = path.read_text().splitlines() if path.exists() else []
    seen = set()
    for i, line in enumerate(lines):
        key = line.split("=", 1)[0].strip()
        if "=" in line and line[0] != "#" and key in values:
            lines[i] = f"{key}={values[key]}"
            seen.add(key)
    extra = [f"{key}={value}" for key, value in values.items() if key not in seen]
    if extra:
        lines += ["", "# Generated by make env", *extra]
    path.write_text("\n".join(lines) + "\n")


def main(target: Path = ENV) -> int:
    current = read(target)
    missing = [key for key in GENERATED if unset(current, key)]
    if missing:
        write(target, {key: GENERATED[key]() for key in missing})
        print(f"Added {len(missing)} generated values to .env: {', '.join(missing)}")
    absent = [key for key in FROM_YOU if unset(current, key)]
    if absent:
        print(f"Add these to .env yourself, then run the command again: {', '.join(absent)}")
        # 2 tells `make env` to start ClickStack, the only place the ingestion key can be copied from.
        return 2 if "HYPERDX_API_KEY" in absent else 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
